-- updated_at triggers
do $$
declare
  table_name text;
begin
  foreach table_name in array array[
    'business_settings','warehouses','product_categories','products','customers',
    'suppliers','sales_invoices','purchase_invoices','cashboxes','expenses',
    'quotations','stock_transfers','stock_counts','installments','cheques'
  ]
  loop
    execute format(
      'create trigger set_updated_at before update on public.%I for each row execute function public.set_updated_at()',
      table_name
    );
  end loop;
end $$;

-- All user-facing business tables are private to the authenticated owner.
do $$
declare
  table_name text;
begin
  foreach table_name in array array[
    'business_settings','warehouses','product_categories','units','products',
    'customers','suppliers','sales_invoices','sales_invoice_items',
    'purchase_invoices','purchase_invoice_items','stock_movements','cashboxes',
    'cash_transactions','expenses','quotations','quotation_items','stock_transfers',
    'stock_transfer_items','stock_counts','stock_count_items','installments',
    'cheques','audit_logs'
  ]
  loop
    execute format('alter table public.%I enable row level security', table_name);
    execute format(
      'create policy %I on public.%I for all to authenticated using ((select auth.uid()) = owner_id) with check ((select auth.uid()) = owner_id)',
      table_name || '_owner_all',
      table_name
    );
  end loop;
end $$;

