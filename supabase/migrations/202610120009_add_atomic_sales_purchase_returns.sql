-- Atomic sales and purchase returns, including stock and cash ledger effects.
create table public.sales_returns (
  id uuid primary key default gen_random_uuid(),
  owner_id uuid not null references auth.users(id) on delete cascade default auth.uid(),
  return_number bigint generated by default as identity,
  sales_invoice_id uuid not null references public.sales_invoices(id) on delete restrict,
  warehouse_id uuid not null references public.warehouses(id) on delete restrict,
  customer_id uuid references public.customers(id) on delete restrict,
  return_date timestamptz not null default now(),
  total numeric(14,2) not null check (total >= 0),
  refund_amount numeric(14,2) not null default 0 check (refund_amount >= 0 and refund_amount <= total),
  cashbox_id uuid references public.cashboxes(id) on delete restrict,
  payment_method text not null default 'cash' check (payment_method in ('cash','card','bank_transfer','cheque','other')),
  notes text,
  status text not null default 'posted' check (status = 'posted'),
  created_at timestamptz not null default now(),
  unique(owner_id, return_number)
);
create table public.sales_return_items (
  id uuid primary key default gen_random_uuid(),
  owner_id uuid not null references auth.users(id) on delete cascade default auth.uid(),
  return_id uuid not null references public.sales_returns(id) on delete cascade,
  sales_invoice_item_id uuid not null references public.sales_invoice_items(id) on delete restrict,
  product_id uuid not null references public.products(id) on delete restrict,
  quantity numeric(14,3) not null check (quantity > 0),
  unit_price numeric(14,2) not null check (unit_price >= 0),
  unit_cost numeric(14,2) not null default 0 check (unit_cost >= 0),
  line_total numeric(14,2) not null check (line_total >= 0),
  created_at timestamptz not null default now()
);
create table public.purchase_returns (
  id uuid primary key default gen_random_uuid(),
  owner_id uuid not null references auth.users(id) on delete cascade default auth.uid(),
  return_number bigint generated by default as identity,
  purchase_invoice_id uuid not null references public.purchase_invoices(id) on delete restrict,
  warehouse_id uuid not null references public.warehouses(id) on delete restrict,
  supplier_id uuid references public.suppliers(id) on delete restrict,
  return_date timestamptz not null default now(),
  total numeric(14,2) not null check (total >= 0),
  received_amount numeric(14,2) not null default 0 check (received_amount >= 0 and received_amount <= total),
  cashbox_id uuid references public.cashboxes(id) on delete restrict,
  payment_method text not null default 'cash' check (payment_method in ('cash','card','bank_transfer','cheque','other')),
  notes text,
  status text not null default 'posted' check (status = 'posted'),
  created_at timestamptz not null default now(),
  unique(owner_id, return_number)
);
create table public.purchase_return_items (
  id uuid primary key default gen_random_uuid(),
  owner_id uuid not null references auth.users(id) on delete cascade default auth.uid(),
  return_id uuid not null references public.purchase_returns(id) on delete cascade,
  purchase_invoice_item_id uuid not null references public.purchase_invoice_items(id) on delete restrict,
  product_id uuid not null references public.products(id) on delete restrict,
  quantity numeric(14,3) not null check (quantity > 0),
  unit_cost numeric(14,2) not null check (unit_cost >= 0),
  line_total numeric(14,2) not null check (line_total >= 0),
  created_at timestamptz not null default now()
);
create index sales_returns_owner_date_idx on public.sales_returns(owner_id, return_date desc);
create index sales_return_items_source_idx on public.sales_return_items(owner_id, sales_invoice_item_id);
create index purchase_returns_owner_date_idx on public.purchase_returns(owner_id, return_date desc);
create index purchase_return_items_source_idx on public.purchase_return_items(owner_id, purchase_invoice_item_id);
alter table public.sales_returns enable row level security;
alter table public.sales_return_items enable row level security;
alter table public.purchase_returns enable row level security;
alter table public.purchase_return_items enable row level security;
create policy sales_returns_owner_all on public.sales_returns for all to authenticated using ((select auth.uid()) = owner_id) with check ((select auth.uid()) = owner_id);
create policy sales_return_items_owner_all on public.sales_return_items for all to authenticated using ((select auth.uid()) = owner_id) with check ((select auth.uid()) = owner_id);
create policy purchase_returns_owner_all on public.purchase_returns for all to authenticated using ((select auth.uid()) = owner_id) with check ((select auth.uid()) = owner_id);
create policy purchase_return_items_owner_all on public.purchase_return_items for all to authenticated using ((select auth.uid()) = owner_id) with check ((select auth.uid()) = owner_id);
grant select, insert, update, delete on public.sales_returns, public.sales_return_items, public.purchase_returns, public.purchase_return_items to authenticated;

create or replace function public.post_sales_return(
  p_sales_invoice_id uuid, p_return_date timestamptz, p_items jsonb,
  p_refund_amount numeric, p_cashbox_id uuid, p_payment_method text, p_notes text
) returns jsonb language plpgsql security invoker set search_path = '' as $$
declare
  v_owner uuid := auth.uid(); v_invoice public.sales_invoices%rowtype; v_return_id uuid; v_return_no bigint;
  v_item jsonb; v_invoice_item_id uuid; v_product_id uuid; v_qty numeric(14,3);
  v_sold numeric(14,3); v_already numeric(14,3); v_price numeric(14,2); v_cost numeric(14,2);
  v_line numeric(14,2); v_total numeric(14,2):=0; v_tracks_stock boolean;
begin
  if v_owner is null then raise exception 'Authentication required'; end if;
  select * into v_invoice from public.sales_invoices where id=p_sales_invoice_id and owner_id=v_owner and status='posted' for update;
  if not found then raise exception 'Posted sales invoice not found'; end if;
  if p_items is null or jsonb_typeof(p_items)<>'array' or jsonb_array_length(p_items)=0 then raise exception 'Return requires items'; end if;
  if p_refund_amount is null or p_refund_amount<0 then raise exception 'Invalid refund amount'; end if;
  if p_payment_method is null or p_payment_method not in ('cash','card','bank_transfer','cheque','other') then raise exception 'Invalid payment method'; end if;
  if p_refund_amount>0 and (p_cashbox_id is null or not exists(select 1 from public.cashboxes where id=p_cashbox_id and owner_id=v_owner and is_active)) then raise exception 'Select an active cashbox for the refund'; end if;
  for v_item in select value from jsonb_array_elements(p_items) loop
    begin v_invoice_item_id := (v_item->>'sales_invoice_item_id')::uuid; v_qty := (v_item->>'quantity')::numeric;
    exception when others then raise exception 'Invalid return item'; end;
    if v_qty<=0 then raise exception 'Return quantity must be positive'; end if;
    if exists(select 1 from jsonb_array_elements(p_items) x where x->>'sales_invoice_item_id'=v_invoice_item_id::text group by x->>'sales_invoice_item_id' having count(*)>1) then raise exception 'Duplicate item in return'; end if;
    select sii.product_id,sii.quantity,sii.unit_price,sii.unit_cost,sii.line_total,p.track_stock
      into v_product_id,v_sold,v_price,v_cost,v_line,v_tracks_stock
      from public.sales_invoice_items sii join public.products p on p.id=sii.product_id and p.owner_id=v_owner
      where sii.id=v_invoice_item_id and sii.invoice_id=v_invoice.id and sii.owner_id=v_owner;
    if not found then raise exception 'Item does not belong to this sales invoice'; end if;
    select coalesce(sum(sri.quantity),0) into v_already from public.sales_return_items sri join public.sales_returns sr on sr.id=sri.return_id and sr.owner_id=v_owner where sri.sales_invoice_item_id=v_invoice_item_id;
    if v_already+v_qty>v_sold then raise exception 'Return quantity exceeds remaining sold quantity for product %',v_product_id; end if;
    v_line := round((select sii.line_total/sii.quantity from public.sales_invoice_items sii where sii.id=v_invoice_item_id)*v_qty,2);
    v_total := v_total+v_line;
    perform pg_advisory_xact_lock(hashtextextended(v_owner::text||':'||v_invoice.warehouse_id::text||':'||v_product_id::text,0));
  end loop;
  if v_total<=0 then raise exception 'Return total must be greater than zero'; end if;
  if p_refund_amount>v_total then raise exception 'Refund cannot exceed return total'; end if;
  insert into public.sales_returns(owner_id,sales_invoice_id,warehouse_id,customer_id,return_date,total,refund_amount,cashbox_id,payment_method,notes)
  values(v_owner,v_invoice.id,v_invoice.warehouse_id,v_invoice.customer_id,coalesce(p_return_date,now()),v_total,p_refund_amount,case when p_refund_amount>0 then p_cashbox_id else null end,p_payment_method,nullif(trim(coalesce(p_notes,'')),''))
  returning id,return_number into v_return_id,v_return_no;
  for v_item in select value from jsonb_array_elements(p_items) loop
    v_invoice_item_id := (v_item->>'sales_invoice_item_id')::uuid; v_qty := (v_item->>'quantity')::numeric;
    select sii.product_id,sii.unit_price,sii.unit_cost,round((sii.line_total/sii.quantity)*v_qty,2),p.track_stock
      into v_product_id,v_price,v_cost,v_line,v_tracks_stock
      from public.sales_invoice_items sii join public.products p on p.id=sii.product_id and p.owner_id=v_owner where sii.id=v_invoice_item_id;
    insert into public.sales_return_items(owner_id,return_id,sales_invoice_item_id,product_id,quantity,unit_price,unit_cost,line_total)
    values(v_owner,v_return_id,v_invoice_item_id,v_product_id,v_qty,v_price,v_cost,v_line);
    if v_tracks_stock then
      insert into public.stock_movements(owner_id,product_id,warehouse_id,movement_type,quantity_delta,unit_cost,reference_type,reference_id,notes)
      values(v_owner,v_product_id,v_invoice.warehouse_id,'sales_return',v_qty,v_cost,'sales_return',v_return_id,'Sales return '||v_return_no::text);
    end if;
  end loop;
  if p_refund_amount>0 then
    insert into public.cash_transactions(owner_id,cashbox_id,transaction_type,amount,payment_method,customer_id,reference_type,reference_id,transaction_date,notes)
    values(v_owner,p_cashbox_id,'other_payment',p_refund_amount,p_payment_method,v_invoice.customer_id,'sales_return',v_return_id,coalesce(p_return_date,now()),'Refund for sales return '||v_return_no::text);
  end if;
  return jsonb_build_object('return_id',v_return_id,'return_number',v_return_no,'total',v_total,'refund_amount',p_refund_amount,'status','posted');
end;
$$;
revoke all on function public.post_sales_return(uuid,timestamptz,jsonb,numeric,uuid,text,text) from public,anon;
grant execute on function public.post_sales_return(uuid,timestamptz,jsonb,numeric,uuid,text,text) to authenticated;

create or replace function public.post_purchase_return(
  p_purchase_invoice_id uuid, p_return_date timestamptz, p_items jsonb,
  p_received_amount numeric, p_cashbox_id uuid, p_payment_method text, p_notes text
) returns jsonb language plpgsql security invoker set search_path = '' as $$
declare
  v_owner uuid := auth.uid(); v_invoice public.purchase_invoices%rowtype; v_return_id uuid; v_return_no bigint;
  v_item jsonb; v_invoice_item_id uuid; v_product_id uuid; v_qty numeric(14,3);
  v_bought numeric(14,3); v_already numeric(14,3); v_cost numeric(14,2);
  v_line numeric(14,2); v_total numeric(14,2):=0; v_available numeric(14,3);
begin
  if v_owner is null then raise exception 'Authentication required'; end if;
  select * into v_invoice from public.purchase_invoices where id=p_purchase_invoice_id and owner_id=v_owner and status='posted' for update;
  if not found then raise exception 'Posted purchase invoice not found'; end if;
  if p_items is null or jsonb_typeof(p_items)<>'array' or jsonb_array_length(p_items)=0 then raise exception 'Return requires items'; end if;
  if p_received_amount is null or p_received_amount<0 then raise exception 'Invalid received amount'; end if;
  if p_payment_method is null or p_payment_method not in ('cash','card','bank_transfer','cheque','other') then raise exception 'Invalid payment method'; end if;
  if p_received_amount>0 and (p_cashbox_id is null or not exists(select 1 from public.cashboxes where id=p_cashbox_id and owner_id=v_owner and is_active)) then raise exception 'Select an active cashbox for the supplier refund'; end if;
  for v_item in select value from jsonb_array_elements(p_items) loop
    begin v_invoice_item_id := (v_item->>'purchase_invoice_item_id')::uuid; v_qty := (v_item->>'quantity')::numeric;
    exception when others then raise exception 'Invalid return item'; end;
    if v_qty<=0 then raise exception 'Return quantity must be positive'; end if;
    if exists(select 1 from jsonb_array_elements(p_items) x where x->>'purchase_invoice_item_id'=v_invoice_item_id::text group by x->>'purchase_invoice_item_id' having count(*)>1) then raise exception 'Duplicate item in return'; end if;
    select pii.product_id,pii.quantity,pii.unit_cost,round(pii.line_total/pii.quantity*v_qty,2)
      into v_product_id,v_bought,v_cost,v_line
      from public.purchase_invoice_items pii where pii.id=v_invoice_item_id and pii.invoice_id=v_invoice.id and pii.owner_id=v_owner;
    if not found then raise exception 'Item does not belong to this purchase invoice'; end if;
    select coalesce(sum(pri.quantity),0) into v_already from public.purchase_return_items pri join public.purchase_returns pr on pr.id=pri.return_id and pr.owner_id=v_owner where pri.purchase_invoice_item_id=v_invoice_item_id;
    if v_already+v_qty>v_bought then raise exception 'Return quantity exceeds remaining purchased quantity for product %',v_product_id; end if;
    perform pg_advisory_xact_lock(hashtextextended(v_owner::text||':'||v_invoice.warehouse_id::text||':'||v_product_id::text,0));
    select coalesce(sum(sm.quantity_delta),0) into v_available from public.stock_movements sm where sm.owner_id=v_owner and sm.product_id=v_product_id and sm.warehouse_id=v_invoice.warehouse_id;
    if v_available<v_qty then raise exception 'Insufficient stock to return product %. Available: %, requested: %',v_product_id,v_available,v_qty; end if;
    v_total := v_total+v_line;
  end loop;
  if v_total<=0 then raise exception 'Return total must be greater than zero'; end if;
  if p_received_amount>v_total then raise exception 'Supplier refund cannot exceed return total'; end if;
  insert into public.purchase_returns(owner_id,purchase_invoice_id,warehouse_id,supplier_id,return_date,total,received_amount,cashbox_id,payment_method,notes)
  values(v_owner,v_invoice.id,v_invoice.warehouse_id,v_invoice.supplier_id,coalesce(p_return_date,now()),v_total,p_received_amount,case when p_received_amount>0 then p_cashbox_id else null end,p_payment_method,nullif(trim(coalesce(p_notes,'')),''))
  returning id,return_number into v_return_id,v_return_no;
  for v_item in select value from jsonb_array_elements(p_items) loop
    v_invoice_item_id := (v_item->>'purchase_invoice_item_id')::uuid; v_qty := (v_item->>'quantity')::numeric;
    select pii.product_id,pii.unit_cost,round(pii.line_total/pii.quantity*v_qty,2) into v_product_id,v_cost,v_line
      from public.purchase_invoice_items pii where pii.id=v_invoice_item_id;
    insert into public.purchase_return_items(owner_id,return_id,purchase_invoice_item_id,product_id,quantity,unit_cost,line_total)
    values(v_owner,v_return_id,v_invoice_item_id,v_product_id,v_qty,v_cost,v_line);
    insert into public.stock_movements(owner_id,product_id,warehouse_id,movement_type,quantity_delta,unit_cost,reference_type,reference_id,notes)
    values(v_owner,v_product_id,v_invoice.warehouse_id,'purchase_return',-v_qty,v_cost,'purchase_return',v_return_id,'Purchase return '||v_return_no::text);
  end loop;
  if p_received_amount>0 then
    insert into public.cash_transactions(owner_id,cashbox_id,transaction_type,amount,payment_method,supplier_id,reference_type,reference_id,transaction_date,notes)
    values(v_owner,p_cashbox_id,'other_receipt',p_received_amount,p_payment_method,v_invoice.supplier_id,'purchase_return',v_return_id,coalesce(p_return_date,now()),'Supplier refund for purchase return '||v_return_no::text);
  end if;
  return jsonb_build_object('return_id',v_return_id,'return_number',v_return_no,'total',v_total,'received_amount',p_received_amount,'status','posted');
end;
$$;
revoke all on function public.post_purchase_return(uuid,timestamptz,jsonb,numeric,uuid,text,text) from public,anon;
grant execute on function public.post_purchase_return(uuid,timestamptz,jsonb,numeric,uuid,text,text) to authenticated;
